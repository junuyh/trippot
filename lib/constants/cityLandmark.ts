//
// ⚠️ 국가 실루엣(countryLandmark.ts)과 역할이 다르다.
//    그쪽은 "이 나라" 를 떠올리게 하는 도형 하나이고, 여기는 **한 도시의
//    랜드마크 여러 개를 한 줄에 세운 스카이라인**이다. 아이콘 세 개가 따로
//    떠 있는 것처럼 보이면 안 되므로 지면선(ground)을 공유한다.
//
// ⚠️ 장식이다. 도시명·여행 정보·금액보다 먼저 눈에 띄면 안 된다.
//    쓰는 쪽에서 불투명도를 매우 낮게 준다. 여기서는 모양만 정의한다.
//
// ⚠️ 외부 URL 을 화면에서 불러오지 않는다. 좌표를 코드로 갖고 있으므로
//    네트워크·에셋 로딩 실패라는 상태 자체가 없다. 등록되지 않은 도시는
//    cityLandmark() 가 null 을 돌려주고, 쓰는 쪽은 배경 없이 그린다.
//    (빈 사각형이나 깨진 이미지가 남지 않는다)
//
// ⚠️ 채움이 아니라 **선**으로 그린다. 인쇄물 느낌을 내려는 것이고,
//    실루엣으로 채우면 같은 낮은 불투명도에서 덩어리로 뭉쳐 보인다.
//
// 도시가 늘면 CITY_LANDMARKS 에 한 줄 추가한다. 좌표계는 아래 VIEW_BOX 이고
// 지면은 y = 150 이다. 새 도시도 지면을 같은 값으로 맞춘다.
// ============================================================================
import { DESTINATION_CODE, type DestinationCode } from "./destinations";

export type CityLandmark = {
  viewBox: string;
  /** 선으로 그릴 path 목록 */
  paths: string[];
};

const VIEW_BOX = "0 0 260 150";

/**
 * 파리 — 개선문 · 에펠탑 · 루브르 피라미드.
 *
 * 왼쪽에서 오른쪽으로 낮음 → 가장 높음 → 낮음 순서로 세워
 * 세 건물이 하나의 스카이라인으로 읽히게 했다.
 */
const PARIS: CityLandmark = {
  viewBox: VIEW_BOX,
  paths: [
    // 공통 지면. 세 랜드마크를 한 줄에 묶는다
    "M4 150 H256",

    // ── 개선문 ──────────────────────────────────────────────────────────
    // 몸통
    "M14 150 V96 H76 V150",
    // 상단 아티크(옥상 부분). 몸통보다 살짝 넓다
    "M8 96 V84 H82 V96",
    // 중앙 아치. y=118 에서 반원으로 열린다
    "M32 150 V118 A13 13 0 0 1 58 118 V150",
    // 몸통 허리선
    "M14 110 H76",

    // ── 에펠탑 ──────────────────────────────────────────────────────────
    // 두 다리. 안쪽으로 휘어 올라간다
    "M100 150 C118 112 130 80 133 46",
    "M172 150 C154 112 142 80 139 46",
    // 1층 전망대와 그 아래 아치
    "M108 114 H164",
    "M111 114 Q136 92 161 114",
    // 2층 전망대
    "M120 78 H152",
    // 상부 기둥과 첨탑
    "M130 60 H142",
    "M133 46 L136 14 L139 46",

    // ── 루브르 피라미드 ────────────────────────────────────────────────
    // 외곽과 중앙 모서리
    "M186 150 L219 100 L252 150",
    "M219 100 V150",
    // 유리 격자
    "M199 130 H239",
    "M206 118 H232",
    "M199 130 L212 150",
    "M206 118 L219 150",
    "M239 130 L226 150",
    "M232 118 L219 150",
  ],
};

const CITY_LANDMARKS: Partial<Record<DestinationCode, CityLandmark>> = {
  [DESTINATION_CODE.PARIS]: PARIS,
};

/** 등록된 도시면 스카이라인을, 아니면 null 을 돌려준다. */
export function cityLandmark(
  code: DestinationCode | null | undefined,
): CityLandmark | null {
  if (!code) return null;
  return CITY_LANDMARKS[code] ?? null;
}
