/** 등록된 도시면 스카이라인을, 아니면 null 을 돌려준다. */
export function cityLandmark(
  code: DestinationCode | null | undefined,
): CityLandmark | null {
  if (!code) return null;
  return CITY_LANDMARKS[code] ?? null;
}
