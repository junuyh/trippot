/** 0 ~ 10. 시트를 열 때 한 번 뽑아 공유·복사가 같은 문구를 쓰게 한다 */
export function pickInviteTemplate(): number {
  return Math.floor(Math.random() * INVITE_TEMPLATES.length);
}

/**
 * 카카오톡·문자에 그대로 붙여 넣는 초대 문구.
 * @param variant INVITE_TEMPLATES 의 번호. 범위를 벗어나면 0
 */
export function buildInviteMessage(
  input: {
    destination: string;
    groupName: string;
    periodLabel: string | null;
    link: string;
  },
  variant = 0,
): string {
  const template = INVITE_TEMPLATES[variant] ?? INVITE_TEMPLATES[0];
  return template
    .replaceAll("{모임명}", input.groupName)
    .replaceAll("{여행명}", input.destination)
    .replaceAll("{여행기간}", input.periodLabel ?? "이번 여행")
    .replaceAll("{초대링크}", input.link);
}
