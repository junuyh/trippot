import * as Linking from "expo-linking";

/** 초대를 받은 사람이 여는 경로. /groups/:groupId/join 은 아직 없다 [팀원] */
export function buildGroupInviteLink(groupId: string): string {
  return Linking.createURL(`/groups/${groupId}/join`);
}

